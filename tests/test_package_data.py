"""What the repository carries: small trained models (no Git LFS: a clone without git-lfs would get
pointer files instead of weights) and notebooks without outputs (they are regenerated by
tools/make_notebooks.py; a notebook saved with its outputs adds megabytes to the history)."""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
DATA = ROOT / "soccercal" / "data"


def test_shipped_models_are_small_real_files():
    files = [p for p in DATA.iterdir() if p.is_file()]
    for p in files:
        assert p.stat().st_size < 2 * 2**20, f"{p.name} is over 2 MB: host it outside git (release / Hugging Face)"
        assert not p.read_bytes()[:40].startswith(b"version https://git-lfs"), f"{p.name} is a Git LFS pointer"
    assert sum(p.stat().st_size for p in files) < 5 * 2**20


def test_shipped_models_are_not_ignored():
    import subprocess

    names = [str(p.relative_to(ROOT)) for p in DATA.iterdir() if p.suffix in (".pt", ".npz")]
    r = subprocess.run(["git", "check-ignore", *names], cwd=ROOT, capture_output=True, text=True)
    assert r.stdout.strip() == "", f"ignored by .gitignore: {r.stdout.split()}"


def test_notebooks_have_no_outputs():
    for nb in (ROOT / "notebooks").glob("*.ipynb"):
        cells = json.loads(nb.read_text())["cells"]
        assert not any(c.get("outputs") for c in cells), f"{nb.name} carries outputs: run tools/make_notebooks.py"
        assert nb.stat().st_size < 200_000
